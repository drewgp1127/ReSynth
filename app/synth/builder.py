"""Build Vital patches from the init preset, without any factory content.

Every ReSynth template starts from `base_patch()`, which gives all templates the same
modulation layout so the parameters in `params.py` mean the same thing in every template:

    env_1 -> amplitude (Vital's built-in amp envelope)
    env_2 -> filter_1_cutoff   (filter envelope; amount 0 = off)
    env_3 -> voice_transpose   (pitch envelope; amount 0 = off)
    lfo_1 -> filter_1_cutoff   (filter LFO, bipolar; amount 0 = off)
    lfo_2 -> voice_transpose   (vibrato, bipolar; amount 0 = off)
    lfo_3 -> voice_amplitude   (tremolo, bipolar; amount 0 = off)

Oscillators use the "Basic Shapes" wavetable, which morphs sine -> triangle -> square -> saw
over the wave-frame control, so the oscillator shape is a continuous searchable parameter.
"""
from __future__ import annotations

import base64
import json
from typing import Any

import numpy as np
import vita

WAVE_SIZE = 2048
# keyframe positions of the Basic Shapes table (frame index 0..255)
SHAPE_FRAMES = {"sine": 0, "triangle": 85, "square": 170, "saw": 255}

STANDARD_MODULATIONS: list[tuple[str, str, bool]] = [
    ("env_2", "filter_1_cutoff", False),
    ("env_3", "voice_transpose", False),
    ("lfo_1", "filter_1_cutoff", True),
    ("lfo_2", "voice_transpose", True),
    ("lfo_3", "voice_amplitude", True),
]


def _b64(wave: np.ndarray) -> str:
    return base64.b64encode(wave.astype("<f4").tobytes()).decode("ascii")


def basic_shapes() -> dict[str, np.ndarray]:
    n = np.arange(WAVE_SIZE) / WAVE_SIZE
    return {
        "sine": np.sin(2 * np.pi * n),
        "triangle": 2 * np.abs(2 * ((n + 0.25) % 1) - 1) - 1,
        "square": np.where(n < 0.5, 1.0, -1.0),
        "saw": 1 - 2 * n,
    }


def wavetable(name: str, frames: list[tuple[int, np.ndarray]]) -> dict[str, Any]:
    """A Vital wavetable dict with one wave-source component and the given keyframes."""
    return {
        "author": "ReSynth",
        "full_normalize": True,
        "remove_all_dc": True,
        "name": name,
        "version": "1.5.5",
        "groups": [{
            "components": [{
                "type": "Wave Source",
                "interpolation": 1,
                "interpolation_style": 1,
                "keyframes": [{"position": int(p), "wave_data": _b64(w)} for p, w in frames],
            }]
        }],
    }


def basic_shapes_table() -> dict[str, Any]:
    shapes = basic_shapes()
    return wavetable("Basic Shapes", [(SHAPE_FRAMES[k], shapes[k]) for k in ("sine", "triangle", "square", "saw")])


def init_patch() -> dict[str, Any]:
    """Vital's init preset as a dict (from vita, so it contains no factory presets)."""
    return json.loads(vita.Synth().to_json())


def base_patch(name: str) -> dict[str, Any]:
    """Init patch with ReSynth's standard routing (see module docstring)."""
    patch = init_patch()
    st = patch["settings"]
    patch["preset_name"] = name
    patch["author"] = "ReSynth"
    patch["comments"] = "Generated by ReSynth from Vital's init patch."
    patch["preset_style"] = ""
    st["wavetables"] = [basic_shapes_table() for _ in range(3)]
    for i in (1, 2, 3):
        st[f"osc_{i}_random_phase"] = 0.0  # deterministic renders
        st[f"osc_{i}_destination"] = 0.0  # FILTER 1
        st[f"osc_{i}_wave_frame"] = float(SHAPE_FRAMES["saw"])
        st[f"osc_{i}_on"] = 1.0 if i == 1 else 0.0
    st["sample_destination"] = 0.0
    st["sample_on"] = 0.0
    st["filter_1_on"] = 1.0
    st["filter_1_cutoff"] = 136.0  # fully open
    st["filter_1_resonance"] = 0.1
    for env in (2, 3):
        st[f"env_{env}_attack"] = 0.0
        st[f"env_{env}_sustain"] = 0.0
        st[f"env_{env}_decay"] = 0.2 ** 0.25
    for lfo in (1, 2, 3):
        st[f"lfo_{lfo}_sync"] = 0.0  # free-running, frequency in Hz (2 ** raw)
        st[f"lfo_{lfo}_frequency"] = float(np.log2(5.0))
    mods = st["modulations"]
    for i, (src, dst, bipolar) in enumerate(STANDARD_MODULATIONS):
        mods[i] = {"source": src, "destination": dst}
        st[f"modulation_{i + 1}_amount"] = 0.0
        st[f"modulation_{i + 1}_bipolar"] = 1.0 if bipolar else 0.0
    return patch


def to_json(patch: dict[str, Any]) -> str:
    return json.dumps(patch)
